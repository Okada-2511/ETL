-- ================================================================
-- POSTGRESQL SETUP: STAGING + CURRENT + AUDIT
-- Bảng nghiệp vụ không bị DROP/REPLACE.
-- Bảng nghiệp vụ chính:
--   public.union_all_data_cap_don   (cấp đơn)
--   public.ds_nhan_su_affina        (nhân sự)
-- Số hợp đồng KHÔNG phải khóa.
-- ================================================================

CREATE SCHEMA IF NOT EXISTS audit;
CREATE SCHEMA IF NOT EXISTS staging;


-- ================================================================
-- PHẦN 1: BẢNG CẤP ĐƠN  →  public.union_all_data_cap_don
