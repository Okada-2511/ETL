    ADD COLUMN IF NOT EXISTS last_synced_at TIMESTAMPTZ;

ALTER TABLE public.union_all_data_cap_don
    ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT TRUE;

-- Các dòng cũ mặc định là active
UPDATE public.union_all_data_cap_don
SET is_active = TRUE
WHERE is_active IS NULL;


-- ----------------------------------------------------------------
-- 1b) Unique index cho source_row_ref (cấp đơn)
-- ----------------------------------------------------------------

CREATE UNIQUE INDEX IF NOT EXISTS ux_union_all_data_cap_don_source_row_ref
ON public.union_all_data_cap_don (source_row_ref)
WHERE source_row_ref IS NOT NULL;


-- ----------------------------------------------------------------
-- 1c) Audit history cho cấp đơn
-- ----------------------------------------------------------------

CREATE TABLE IF NOT EXISTS audit.union_all_data_cap_don_history (
    history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_id          BIGINT,
    source_row_ref  TEXT,
    operation       TEXT NOT NULL,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    old_data        JSONB,
    new_data        JSONB
);


-- ----------------------------------------------------------------
-- 1d) Function ghi lịch sử thay đổi (cấp đơn)
-- ----------------------------------------------------------------

CREATE OR REPLACE FUNCTION audit.log_union_all_data_cap_don_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    IF TG_OP = 'UPDATE' THEN

        IF OLD.row_hash IS NOT DISTINCT FROM NEW.row_hash THEN
            RETURN NEW;
        END IF;

        INSERT INTO audit.union_all_data_cap_don_history (
            row_id, source_row_ref, operation, old_data, new_data
        )
        VALUES (
            OLD.row_id,
            COALESCE(NEW.source_row_ref, OLD.source_row_ref),
            'UPDATE',
            to_jsonb(OLD) - ARRAY[
                'row_id','source_sheet','source_row_number',
                'source_row_ref','row_hash','last_synced_at','is_active'
            ],
            to_jsonb(NEW) - ARRAY[
                'row_id','source_sheet','source_row_number',
                'source_row_ref','row_hash','last_synced_at','is_active'
            ]
        );
        RETURN NEW;

    ELSIF TG_OP = 'INSERT' THEN

        INSERT INTO audit.union_all_data_cap_don_history (
            row_id, source_row_ref, operation, new_data
        )
        VALUES (
            NEW.row_id,
            NEW.source_row_ref,
            'INSERT',
            to_jsonb(NEW) - ARRAY[
                'row_id','source_sheet','source_row_number',
                'source_row_ref','row_hash','last_synced_at','is_active'
            ]
        );
        RETURN NEW;

    ELSIF TG_OP = 'DELETE' THEN

        INSERT INTO audit.union_all_data_cap_don_history (
            row_id, source_row_ref, operation, old_data
        )
        VALUES (
            OLD.row_id,
            OLD.source_row_ref,
            'DELETE',
            to_jsonb(OLD) - ARRAY[
                'row_id','source_sheet','source_row_number',
                'source_row_ref','row_hash','last_synced_at','is_active'
            ]
        );
        RETURN OLD;

    END IF;

    RETURN NULL;
END;
$$;


-- ----------------------------------------------------------------
-- 1e) Trigger audit cho union_all_data_cap_don
-- ----------------------------------------------------------------

DROP TRIGGER IF EXISTS trg_union_all_data_cap_don_audit
ON public.union_all_data_cap_don;

CREATE TRIGGER trg_union_all_data_cap_don_audit
AFTER INSERT OR UPDATE OR DELETE
ON public.union_all_data_cap_don
FOR EACH ROW
EXECUTE FUNCTION audit.log_union_all_data_cap_don_change();


